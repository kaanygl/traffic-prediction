    # Concatenate all batches
    preds = np.concatenate(preds, axis=0).squeeze(-1)
    actuals = np.concatenate(actuals, axis=0)

    # 5. Inverse Transform to get Real Traffic Flow
    # We construct dummy arrays because scaler expects (N, Features)
    dummy_preds = np.zeros((preds.size, F))
    dummy_actuals = np.zeros((actuals.size, F))

    # Target variable is at index 0
    dummy_preds[:, 0] = preds.flatten()
    dummy_actuals[:, 0] = actuals.flatten()

    inv_preds = scaler.inverse_transform(dummy_preds)[:, 0]
    inv_actuals = scaler.inverse_transform(dummy_actuals)[:, 0]

    # 6. Calculate Metrics
    mse = mean_squared_error(inv_actuals, inv_preds)
    rmse = np.sqrt(mse)
    mae = mean_absolute_error(inv_actuals, inv_preds)
    r2 = r2_score(inv_actuals, inv_preds)

