class DGATNet(nn.Module):
    def __init__(self, num_nodes, num_features, hidden_dim=128, heads=4, k_neighbors=20):
        super(DGATNet, self).__init__()
        self.num_nodes = num_nodes
        self.input_proj = nn.Linear(num_features, hidden_dim)
        self.graph_learner = DynamicGraphLearner(hidden_dim, hidden_dim // 2, k_neighbors)
        self.gat = GATv2Conv(hidden_dim, hidden_dim // heads, heads=heads, concat=True)

        encoder_layer = nn.TransformerEncoderLayer(d_model=hidden_dim, nhead=heads, batch_first=True)
        self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=2)

        self.fc1 = nn.Linear(hidden_dim, 32)
        self.fc2 = nn.Linear(32, 1)
        self.norm = nn.LayerNorm(hidden_dim)

    def forward(self, x):
        batch_size, num_nodes, seq_len, _ = x.shape
        x = self.input_proj(x)
        x_context = x.mean(dim=2)

        spatial_outputs = []
        for b in range(batch_size):
            adj = self.graph_learner(x_context[b])
            edge_index, _ = dense_to_sparse(adj)
            edge_index = edge_index.to(x.device)
            out_gat = self.gat(x[b, :, -1, :], edge_index)
            spatial_outputs.append(out_gat)

        x_spatial = torch.stack(spatial_outputs)
        x_spatial = self.norm(x_spatial + x[:, :, -1, :])

        x_spatial = x_spatial.view(batch_size * num_nodes, 1, -1)
        x_temporal = self.transformer(x_spatial)
        x_temporal = x_temporal.view(batch_size, num_nodes, -1)

        out = F.relu(self.fc1(x_temporal))
        out = self.fc2(out)
        return out

