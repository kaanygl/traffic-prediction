def main():
    gc.collect()
    torch.cuda.empty_cache()

    # 1. Load Data
    data, split_idx, static_df, feature_cols = load_and_process_data()
    if data is None: return

    # 2. Scale
    scaler = StandardScaler()
    N, T, F = data.shape
    data_flat = data.reshape(-1, F)
    data_scaled = scaler.fit_transform(data_flat).reshape(N, T, F).astype(np.float32)

    # 3. Build Adjacency Matrix (Static)
    adj_mx = build_adjacency_matrix(static_df, K_NEIGHBORS, GAUSSIAN_SIGMA)

    # 4. Create Datasets
    X_train, y_train, X_test, y_test = create_dataset(data_scaled, split_idx)
    print(f"Train shape: {X_train.shape}, Test shape: {X_test.shape}")

    train_loader = DataLoader(TensorDataset(X_train, y_train), batch_size=BATCH_SIZE, shuffle=True)
    test_loader = DataLoader(TensorDataset(X_test, y_test), batch_size=BATCH_SIZE, shuffle=False)

    # 5. Model Init
    num_nodes = X_train.shape[3] # Nodes are at index 3 in [B, C, T, N]
    num_features = X_train.shape[1] # Features at index 1

    model = STGCN(num_nodes, num_features, SEQUENCE_LENGTH, adj_mx).to(DEVICE)
    optimizer = torch.optim.Adam(model.parameters(), lr=LEARNING_RATE)
    criterion = nn.MSELoss()
    grad_scaler = torch.cuda.amp.GradScaler()
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode='min', factor=0.5, patience=3)

    print("\nSTARTING STGCN TRAINING")
    best_val_loss = float('inf')

    for epoch in range(EPOCHS):
        model.train()
        train_loss = 0
        optimizer.zero_grad()

        for i, (X_batch, y_batch) in enumerate(tqdm(train_loader, desc=f"Epoch {epoch+1}", leave=False)):
            X_batch, y_batch = X_batch.to(DEVICE), y_batch.to(DEVICE)

            with torch.cuda.amp.autocast():
                out = model(X_batch)
                loss = criterion(out, y_batch)
                loss = loss / GRAD_ACCUM_STEPS # Normalize

            grad_scaler.scale(loss).backward()

            if (i + 1) % GRAD_ACCUM_STEPS == 0:
                grad_scaler.step(optimizer)
                grad_scaler.update()
                optimizer.zero_grad()

            train_loss += loss.item() * GRAD_ACCUM_STEPS

        avg_train_loss = train_loss / len(train_loader)

        # Validation
        model.eval()
        val_loss = 0
        with torch.no_grad():
            for X_batch, y_batch in test_loader:
                X_batch, y_batch = X_batch.to(DEVICE), y_batch.to(DEVICE)
                with torch.cuda.amp.autocast():
                    out = model(X_batch)
                    loss = criterion(out, y_batch)
                val_loss += loss.item()

        avg_val_loss = val_loss / len(test_loader)
        current_lr = optimizer.param_groups[0]['lr']
        print(f"Epoch {epoch+1}: Train Loss: {avg_train_loss:.4f} | Val Loss: {avg_val_loss:.4f} | LR: {current_lr:.6f}")

        scheduler.step(avg_val_loss)

        if avg_val_loss < best_val_loss:
            best_val_loss = avg_val_loss
            torch.save(model.state_dict(), 'best_stgcn_model.pth')
            # Also save the adjacency matrix for inference
            torch.save(adj_mx, 'stgcn_adj_matrix.pt')

    # Save Artifacts for App
    print("\nSaving artifacts...")
    with open('scalers.pkl', 'wb') as f:
        pickle.dump(scaler, f)

    static_df.reset_index().to_pickle('sensor_static_data.pkl')
    print("✓ Saved scalers.pkl, sensor_static_data.pkl, stgcn_adj_matrix.pt")

if __name__ == "__main__":
    main()

