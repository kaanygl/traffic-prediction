def build_adjacency_matrix(static_df, k_neighbors, sigma):
    print("Building spatial graph (k-NN)...")
    coords = np.radians(static_df[['LATITUDE', 'LONGITUDE']].values)

    # Build k-NN graph
    adj_sparse = kneighbors_graph(coords, n_neighbors=k_neighbors, mode='distance', metric='haversine')

    # Gaussian kernel weighting
    # Distance in 'adj_sparse' is in radians. Multiply by Earth radius (6371 km)
    dists = adj_sparse.data * 6371.0
    adj_sparse.data = np.exp(- (dists**2) / (sigma**2))

    # Convert to dense tensor for STGCN
    adj_dense = torch.from_numpy(adj_sparse.toarray()).float()

    # Add self-loops (identity matrix)
    adj_dense = adj_dense + torch.eye(adj_dense.shape[0])

    # Normalize: D^-0.5 * A * D^-0.5 (Chebyshev approximation usually requires normalized Laplacian)
    # But for standard GCN/STGCN, row-normalization or symmetric norm is common.
    # Here we use symmetric normalization.
    rowsum = adj_dense.sum(1)
    d_inv_sqrt = torch.pow(rowsum, -0.5)
    d_inv_sqrt[torch.isinf(d_inv_sqrt)] = 0.
    d_mat_inv_sqrt = torch.diag(d_inv_sqrt)
    norm_adj = torch.mm(torch.mm(d_mat_inv_sqrt, adj_dense), d_mat_inv_sqrt)

    return norm_adj.to(DEVICE)

def create_dataset(data, split_idx):
    num_timesteps = data.shape[0]
    X_list, y_list = [], []

    # STGCN usually expects [Batch, 1, Time, Nodes] or [Batch, Features, Time, Nodes]
    # We will format as: [Batch, Time, Nodes, Features] first, then permute in the model or here.
    # Let's permute here to: [Batch, Features, Time, Nodes] which is standard for Conv2d based STGCNs

    for i in range(num_timesteps - SEQUENCE_LENGTH - PREDICTION_HORIZON + 1):
        X_list.append(data[i : i+SEQUENCE_LENGTH])
        y_list.append(data[i+SEQUENCE_LENGTH+PREDICTION_HORIZON-1, :, 0]) # Target is idx 0

    X = np.array(X_list, dtype=np.float32) # [Batch, Time, Nodes, Features]
    y = np.array(y_list, dtype=np.float32) # [Batch, Nodes]

    # Permute X to [Batch, Features, Time, Nodes]
    # Current: [B, T, N, F] -> Permute(0, 3, 1, 2)
    X = torch.from_numpy(X).permute(0, 3, 1, 2)
    y = torch.from_numpy(y)

    train_len = split_idx - SEQUENCE_LENGTH

    return X[:train_len], y[:train_len], X[train_len:], y[train_len:]

