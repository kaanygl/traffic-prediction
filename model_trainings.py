class TemporalConvLayer(nn.Module):
    def __init__(self, in_channels, out_channels, kernel_size=3):
        super(TemporalConvLayer, self).__init__()
        self.conv_1 = nn.Conv2d(in_channels, out_channels, (1, kernel_size))
        self.conv_2 = nn.Conv2d(in_channels, out_channels, (1, kernel_size))
        self.conv_3 = nn.Conv2d(in_channels, out_channels, (1, kernel_size))

    def forward(self, x):
        # x: [Batch, C, Nodes, Time]
        p = self.conv_1(x)
        q = torch.sigmoid(self.conv_2(x))
        r = torch.tanh(self.conv_3(x))
        return p * q * r

class STGCNBlock(nn.Module):
    def __init__(self, in_channels, spatial_channels, temporal_channels, num_nodes, adj_mx):
        super(STGCNBlock, self).__init__()
        self.adj_mx = adj_mx
        self.temporal_1 = TemporalConvLayer(in_channels, spatial_channels)
        self.theta = nn.Parameter(torch.FloatTensor(spatial_channels, spatial_channels))
        self.temporal_2 = TemporalConvLayer(spatial_channels, temporal_channels)
        self.batch_norm = nn.BatchNorm2d(num_nodes)
        self.reset_parameters()

    def reset_parameters(self):
        stdv = 1. / np.sqrt(self.theta.shape[1])
        self.theta.data.uniform_(-stdv, stdv)

    def forward(self, x):
        # x: [Batch, C, Nodes, Time]

        # 1. Temporal Conv
        t1 = self.temporal_1(x) # [Batch, SpatialC, Nodes, T_new]

        # 2. Spatial Graph Conv (GCN)
        # Graph Conv: AXW
        # Permute for multiplication: [Batch, T_new, Nodes, SpatialC]
        t1_perm = t1.permute(0, 3, 2, 1)
        # AX (using broadcasting)
        # adj_mx: [Nodes, Nodes]
        # We need [Batch, T_new, Nodes, SpatialC]
        # Matmul (Nodes,Nodes) * (..., Nodes, SpatialC) -> (..., Nodes, SpatialC)
        ax = torch.matmul(self.adj_mx, t1_perm)
        # AXW
        axw = torch.matmul(ax, self.theta)

        # Permute back: [Batch, SpatialC, Nodes, T_new]
        gcn_out = axw.permute(0, 3, 2, 1)

        # 3. Temporal Conv 2
        t2 = F.relu(gcn_out)
        t2 = self.temporal_2(t2)

        return self.batch_norm(t2)

class STGCN(nn.Module):
    def __init__(self, num_nodes, in_channels, time_steps, adj_mx):
        super(STGCN, self).__init__()
        self.adj_mx = adj_mx

        # Block 1
        # Input: [B, F, N, T]
        # Temporal Conv reduces time dim by (kernel_size - 1)
        # We use kernel=3, so T -> T-2
        self.block1 = STGCNBlock(in_channels, 64, 64, num_nodes, adj_mx)

        # Block 2
        # T-2 -> T-4
        self.block2 = STGCNBlock(64, 64, 64, num_nodes, adj_mx)

        # Output layers
        last_time_dim = time_steps - 4 # Two blocks with kernel 3
        self.final_conv = nn.Conv2d(64, 64, (1, last_time_dim))
        self.fc = nn.Linear(64, 1)

    def forward(self, x):
        # x: [Batch, Features, Time, Nodes] -> Permute to [Batch, Features, Nodes, Time]
        x = x.permute(0, 1, 3, 2)

        out1 = self.block1(x)
        out2 = self.block2(out1)

        # Flatten time dimension
        out3 = self.final_conv(out2) # [Batch, 64, Nodes, 1]
        out3 = out3.permute(0, 2, 3, 1) # [Batch, Nodes, 1, 64]
        out3 = self.fc(out3) # [Batch, Nodes, 1, 1]

        return out3.squeeze(-1).squeeze(-1) # [Batch, Nodes]

