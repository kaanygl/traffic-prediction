def main():
    gc.collect()
    torch.cuda.empty_cache()

    data, split_idx = load_and_process_data()
    if data is None: return

    scaler = StandardScaler()
    N, T, F = data.shape
    data_flat = data.reshape(-1, F)
    data_scaled = scaler.fit_transform(data_flat).reshape(N, T, F)

    X_train, y_train, X_test, y_test = create_dataset(data_scaled, split_idx)
    print(f"Train shape: {X_train.shape}, Test shape: {X_test.shape}")

    train_loader = DataLoader(TensorDataset(X_train, y_train), batch_size=BATCH_SIZE, shuffle=True)
    test_loader = DataLoader(TensorDataset(X_test, y_test), batch_size=BATCH_SIZE, shuffle=False)

    num_nodes = X_train.shape[1]
    num_features = X_train.shape[3]

    model = DGATNet(num_nodes, num_features, HIDDEN_DIM, HEADS, K_NEIGHBORS).to(DEVICE)
    optimizer = torch.optim.Adam(model.parameters(), lr=LEARNING_RATE, weight_decay=1e-5)
    criterion = nn.MSELoss()
    grad_scaler = torch.cuda.amp.GradScaler()

    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, mode='min', factor=0.5, patience=7
    )

    early_stop_patience = 10
    early_stop_counter = 0
    best_val_loss = float('inf')
    best_model_path = 'best_dgat_model.pth'

    print("\nSTARTING OPTIMIZED DGAT-NET TRAINING (AMP + Low Batch Size)")
    history = {'loss': [], 'val_loss': []}

    for epoch in range(EPOCHS):
        model.train()
        train_loss = 0

        for X_batch, y_batch in tqdm(train_loader, desc=f"Epoch {epoch+1}", leave=False):
            X_batch, y_batch = X_batch.to(DEVICE), y_batch.to(DEVICE)

            optimizer.zero_grad()

            with torch.cuda.amp.autocast():
                out = model(X_batch)
                loss = criterion(out.squeeze(-1), y_batch)

            grad_scaler.scale(loss).backward()
            grad_scaler.unscale_(optimizer)
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            grad_scaler.step(optimizer)
            grad_scaler.update()

            train_loss += loss.item()

        avg_train_loss = train_loss / len(train_loader)

        model.eval()
        val_loss = 0
        with torch.no_grad():
            for X_batch, y_batch in test_loader:
                X_batch, y_batch = X_batch.to(DEVICE), y_batch.to(DEVICE)
                with torch.cuda.amp.autocast():
                    out = model(X_batch)
                    loss = criterion(out.squeeze(-1), y_batch)
                val_loss += loss.item()

        avg_val_loss = val_loss / len(test_loader)

        history['loss'].append(avg_train_loss)
        history['val_loss'].append(avg_val_loss)

        # --- UPDATED PRINT STATEMENT ---
        current_lr = optimizer.param_groups[0]['lr']
        print(f"Epoch {epoch+1}: Train Loss: {avg_train_loss:.4f} | Val Loss: {avg_val_loss:.4f} | LR: {current_lr:.6f} | Patience: {early_stop_counter}/{early_stop_patience}")

        scheduler.step(avg_val_loss)

        if avg_val_loss < best_val_loss:
            best_val_loss = avg_val_loss
            early_stop_counter = 0
            torch.save(model.state_dict(), best_model_path)
        else:
            early_stop_counter += 1

        if early_stop_counter >= early_stop_patience:
            print(f"Early stopping at epoch {epoch+1}")
            break

    print("\nLoading best model...")
    model.load_state_dict(torch.load(best_model_path))
    model.eval()

    preds, actuals = [], []
    with torch.no_grad():
        for X_batch, y_batch in test_loader:
            X_batch = X_batch.to(DEVICE)
            with torch.cuda.amp.autocast():
                out = model(X_batch).cpu().float().numpy().squeeze(-1)
            preds.append(out)
            actuals.append(y_batch.numpy())

    preds = np.concatenate(preds, axis=0)
    actuals = np.concatenate(actuals, axis=0)

    dummy_pred = np.zeros((preds.size, F))
    dummy_actual = np.zeros((actuals.size, F))
    dummy_pred[:, 0] = preds.flatten()
    dummy_actual[:, 0] = actuals.flatten()

    inv_pred = scaler.inverse_transform(dummy_pred)[:, 0]
    inv_actual = scaler.inverse_transform(dummy_actual)[:, 0]

    rmse = np.sqrt(mean_squared_error(inv_actual, inv_pred))
    r2 = r2_score(inv_actual, inv_pred)

    print(f"\nFINAL RESULTS: RMSE: {rmse:.4f}, R2: {r2:.4f}")

    plt.figure(figsize=(10, 8))
    sample_size = min(10000, len(inv_actual))
    indices = np.random.choice(len(inv_actual), sample_size, replace=False)

    plt.scatter(inv_actual[indices], inv_pred[indices], alpha=0.5, s=10)
    min_val = min(inv_actual[indices].min(), inv_pred[indices].min())
    max_val = max(inv_actual[indices].max(), inv_pred[indices].max())
    plt.plot([min_val, max_val], [min_val, max_val], 'r--', lw=2, label='Perfect')

    plt.xlabel('Actual Flow')
    plt.ylabel('Predicted Flow')
    plt.title(f'DGAT-Net Predictions (R² = {r2:.3f})')
    plt.legend()
    plt.savefig('dgat_predictions_scatter.png')
    print("✓ Saved scatter plot")

