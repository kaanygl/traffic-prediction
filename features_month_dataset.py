    def _spatial_sample(self, df, n_samples):
        """
        Stratified spatial sampling to ensure coverage
        """
        # Create spatial grid
        n_bins = int(np.sqrt(n_samples))

        lat_bins = pd.cut(df['LATITUDE'], bins=n_bins, labels=False)
        lon_bins = pd.cut(df['LONGITUDE'], bins=n_bins, labels=False)
        df['spatial_bin'] = lat_bins.astype(str) + '_' + lon_bins.astype(str)

        # Sample from each bin
        samples_per_bin = max(1, n_samples // len(df['spatial_bin'].unique()))

        sampled = df.groupby('spatial_bin', group_keys=False).apply(
            lambda x: x.sample(min(len(x), samples_per_bin), random_state=42)
        )

        # If we need more samples, add random ones
        if len(sampled) < n_samples:
            remaining = df[~df.index.isin(sampled.index)]
            extra = remaining.sample(min(len(remaining), n_samples - len(sampled)), random_state=42)
            sampled = pd.concat([sampled, extra])

        return sampled.drop('spatial_bin', axis=1)

    def _knn_impute_features(self, all_sensors, sampled_sensors, feature_df, k=5):
        """
        VECTORIZED KNN imputation for missing features
        """
        # Get coordinates
        all_coords = all_sensors[['LATITUDE', 'LONGITUDE']].values
        sampled_coords = sampled_sensors[['LATITUDE', 'LONGITUDE']].values

        # Build KDTree
        tree = cKDTree(sampled_coords)

        # Find non-sampled sensors
        non_sampled = all_sensors[~all_sensors['GEOHASH'].isin(sampled_sensors['GEOHASH'])]
        non_sampled_coords = non_sampled[['LATITUDE', 'LONGITUDE']].values

        # Query k nearest neighbors for all non-sampled at once
        distances, indices = tree.query(non_sampled_coords, k=k)

        # Get feature columns (exclude GEOHASH)
        feature_cols = [col for col in feature_df.columns if col != 'GEOHASH']

        # Impute features
        imputed_rows = []
        for i, geohash in enumerate(non_sampled['GEOHASH'].values):
            # Get k nearest sampled sensors
            nn_geohashes = sampled_sensors.iloc[indices[i]]['GEOHASH'].values
            nn_features = feature_df[feature_df['GEOHASH'].isin(nn_geohashes)]

            # Average their features
            imputed_features = nn_features[feature_cols].mean()
            imputed_features['GEOHASH'] = geohash

            imputed_rows.append(imputed_features)

        # Combine with original
        imputed_df = pd.DataFrame(imputed_rows)
        result = pd.concat([feature_df, imputed_df], ignore_index=True)

