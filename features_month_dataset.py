def add_one_hot_encoding(df, categorical_columns=['time_period']):
    """
    Add one-hot encoding for categorical temporal features
    Use this if you're using traditional ML models (LightGBM, XGBoost)
    """
    df = df.copy()

    for col in categorical_columns:
        if col in df.columns:
            # Create dummy variables
            dummies = pd.get_dummies(df[col], prefix=col)
            df = pd.concat([df, dummies], axis=1)

    return df

